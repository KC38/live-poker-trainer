#!/usr/bin/env python3
"""Cache key for the native iOS simulator build of a checkout.

A debug ``Runner.app`` only has to be rebuilt by Xcode when native inputs
change: plugin versions (``pubspec.lock``), the ``ios/`` project, or the
Flutter engine. Dart under ``lib/`` and assets are synced by the Flutter
tool at runtime, so two checkouts with the same key can share one prebuilt
``Runner.app`` (``flutter run --use-application-binary``).

Usage:
    python3 tools/native_build_key.py [checkout]
"""

from __future__ import annotations

import argparse
import hashlib
import os
import subprocess
import sys
from pathlib import Path

NATIVE_PATHS = ("ios", "pubspec.lock")

# Regenerated by `pod install` / Xcode on every machine; refresh-simulator
# discards them as machine dirt, so they must not split the cache.
IGNORED_DIRT = (
    "ios/Podfile.lock",
    "ios/Runner.xcodeproj/project.pbxproj",
)


def _git(checkout: Path, *args: str) -> bytes:
    """Run git in [checkout] and return stdout bytes."""
    return subprocess.run(
        ["git", "-C", str(checkout), *args],
        check=True,
        capture_output=True,
    ).stdout


def _engine_version() -> str:
    """Return the Flutter engine revision the tool would embed."""
    root = os.environ.get("FLUTTER_ROOT", "")
    candidates = []
    if root:
        candidates.append(Path(root) / "bin/internal/engine.version")
    flutter = subprocess.run(
        ["/bin/sh", "-c", "command -v flutter"],
        capture_output=True,
        text=True,
    ).stdout.strip()
    if flutter:
        real = Path(flutter).resolve()
        candidates.append(real.parent / "internal/engine.version")
    candidates.append(
        Path("/opt/homebrew/share/flutter/bin/internal/engine.version")
    )
    for path in candidates:
        if path.is_file():
            return path.read_text(encoding="utf-8").strip()
    return "unknown-engine"


def native_build_key(checkout: Path) -> str:
    """Hash committed native inputs plus intentional uncommitted edits."""
    digest = hashlib.sha256()
    digest.update(_engine_version().encode())
    digest.update(_git(checkout, "ls-tree", "-r", "HEAD", "--", *NATIVE_PATHS))
    excludes = [f":(exclude){path}" for path in IGNORED_DIRT]
    digest.update(
        _git(checkout, "diff", "HEAD", "--binary", "--", *NATIVE_PATHS, *excludes)
    )
    return digest.hexdigest()[:20]


def main(argv: list[str]) -> int:
    """CLI: print the key for a checkout (default: cwd)."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("checkout", nargs="?", default=".", type=Path)
    args = parser.parse_args(argv)
    try:
        print(native_build_key(args.checkout))
    except subprocess.CalledProcessError as exc:
        print(f"native_build_key: git failed: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
